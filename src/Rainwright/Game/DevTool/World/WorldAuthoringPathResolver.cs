using System;
using System.Collections.Generic;
using System.IO;

namespace DryCycle.DevUI.DevTool.World;

/// <summary>
/// Resolves editable Rain World world-data files back to their real mod source instead of the
/// generated mergedmods cache returned first by AssetManager.ResolveFilePath.
///
/// Existing author files keep their native writer. A region's content Mod is inferred automatically;
/// inherited files without an owned source use existing community modify rules, while Remix caches stay read-only.
/// </summary>
internal static class WorldAuthoringPathResolver
{
    internal static string ResolveExistingSource(string relativePath)
    {
        using var discoveryTiming = Core.EditorSlowOperation.Measure("Map.Open.AuthorSourceDiscovery");
        if (string.IsNullOrWhiteSpace(relativePath))
            return string.Empty;

        string normalized = relativePath
            .Replace('/', Path.DirectorySeparatorChar)
            .Replace('\\', Path.DirectorySeparatorChar);
        bool worldFile = normalized.StartsWith("world" + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase);

        // Infer the region owner from world files/room directories; no manual Mod selection.
        if (worldFile &&
            normalized.EndsWith(".txt", StringComparison.OrdinalIgnoreCase))
        {
            string author = WorldModificationWorkspace.Resolve(normalized);
            if (!string.IsNullOrWhiteSpace(author)) return author;
        }

        try
        {
            if (ModManager.ActiveMods != null)
            {
                for (int i = ModManager.ActiveMods.Count - 1; i >= 0; i--)
                {
                    ModManager.Mod mod = ModManager.ActiveMods[i];
                    if (mod == null || worldFile && !WorldModificationWorkspace.IsContentMod(mod)) continue;

                    if (!worldFile && mod.hasTargetedVersionFolder)
                    {
                        string owned = FindExistingOwnedSource(mod.TargetedPath, normalized);
                        if (owned != null) return owned;
                    }

                    if (!worldFile && mod.hasNewestFolder)
                    {
                        string owned = FindExistingOwnedSource(mod.NewestPath, normalized);
                        if (owned != null) return owned;
                    }

                    string baseOwned = FindExistingOwnedSource(mod.path, normalized);
                    if (baseOwned != null) return baseOwned;
                }
            }
        }
        catch (Exception error)
        {
            global::DryCycle.DevUI.DevTool.Core.EditorDiagnostics.Warning(
                "World authoring source resolution failed for '" + relativePath + "'.", error);
        }

        // AssetManager.ResolveFilePath can point into the base game or an overlay generated by
        // another Mod. Neither is proof of author ownership; callers must fail visibly instead
        // of treating a read location as a writable source.
        return string.Empty;
    }

    /// <summary>
    /// A crash snapshot is historical data, not a permanent capability to write.
    /// Require the destination to be an existing source in an active Mod and the
    /// current highest-priority author file for the same relative path.
    /// No mergedmods, base-game or disabled Mod paths are authorized.
    /// </summary>
    internal static bool TryAuthorizeRecoveryTarget(string target, out string error) =>
        TryAuthorizeRecoveryTarget(target, out _, out error);

    internal static bool TryAuthorizeRecoveryTarget(
        string target, out string ownerModId, out string error)
    {
        ownerModId = string.Empty;
        error = "Recovery refused: the target is not the current writable source of an active Mod.";
        if (string.IsNullOrWhiteSpace(target) || !Path.IsPathRooted(target))
            return false;

        try
        {
            string fullTarget = Path.GetFullPath(target);
            if (WorldModificationWorkspace.IsVersionedWorldSource(fullTarget)) return false;
            if (WorldModificationWorkspace.TryAuthorizeVariant(fullTarget, out ownerModId)) { error = null; return true; }
            if (WorldModificationWorkspace.TryAuthorize(fullTarget, out ownerModId) ||
                WorldModificationWorkspace.TryAuthorizeBackground(fullTarget, out ownerModId))
            {
                error = null;
                return true;
            }
            if (IsMergedCachePath(fullTarget) || !File.Exists(fullTarget))
                return false;

            var activeMods = ModManager.ActiveMods;
            if (activeMods == null || activeMods.Count == 0)
                return false;

            // Windows author files are case-insensitive, while Linux file names
            // are case-sensitive. Do not accept a differently cased sibling on Linux.
            StringComparison pathComparison = Path.DirectorySeparatorChar == '\\'
                ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
            for (int i = activeMods.Count - 1; i >= 0; i--)
            {
                ModManager.Mod mod = activeMods[i];
                if (mod == null) continue;
                string[] roots =
                {
                    mod.hasTargetedVersionFolder ? mod.TargetedPath : null,
                    mod.hasNewestFolder ? mod.NewestPath : null,
                    mod.path
                };
                foreach (string root in roots)
                {
                    if (string.IsNullOrWhiteSpace(root)) continue;
                    string fullRoot = Path.GetFullPath(root)
                        .TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
                    string prefix = fullRoot + Path.DirectorySeparatorChar;
                    if (!fullTarget.StartsWith(prefix, pathComparison)) continue;

                    string relative = fullTarget.Substring(prefix.Length);
                    if (!global::RainWright.IO.AuthoringSourcePaths.TryCombineUnderModRoot(
                            root, relative, out string candidate) ||
                        !string.Equals(candidate, fullTarget, pathComparison) ||
                        !global::RainWright.IO.AuthoringSourcePaths.IsUnredirectedExistingModSource(
                            root, relative, fullTarget))
                        continue;

                    // ResolveExistingSource observes active Mod order and targeted /
                    // newest precedence. A newly overlaid source must not allow an
                    // old snapshot to write back to the hidden lower-priority file.
                    string current = ResolveExistingSource(relative);
                    if (string.Equals(current, fullTarget, pathComparison))
                    {
                        ownerModId = mod.id ?? string.Empty;
                        error = null;
                        return true;
                    }
                }
            }
        }
        catch (Exception ex)
        {
            global::DryCycle.DevUI.DevTool.Core.EditorDiagnostics.Warning(
                "Recovery author source validation failed.", ex);
        }
        return false;
    }

    private static string FindExistingOwnedSource(string modRoot, string relativePath)
    {
        if (!global::RainWright.IO.AuthoringSourcePaths.TryCombineUnderModRoot(
                modRoot, relativePath, out string candidate))
            return null;

        return !IsMergedCachePath(candidate) && File.Exists(candidate) &&
               global::RainWright.IO.AuthoringSourcePaths.IsUnredirectedExistingModSource(modRoot, relativePath, candidate)
            ? candidate
            : null;
    }

    internal static bool TryResolveMapConfigSource(
        string regionName,
        string resolvedMapPath,
        out string sourcePath,
        out string error)
    {
        sourcePath = string.Empty;
        error = null;

        if (string.IsNullOrWhiteSpace(regionName) || string.IsNullOrWhiteSpace(resolvedMapPath))
        {
            error = "Map config region or resolved path is unavailable.";
            return false;
        }

        string fileName = Path.GetFileName(resolvedMapPath);
        if (string.IsNullOrWhiteSpace(fileName))
        {
            error = "Map config file name could not be resolved.";
            return false;
        }

        string relativePath =
            "World" + Path.DirectorySeparatorChar +
            regionName + Path.DirectorySeparatorChar +
            fileName;
        sourcePath = ResolveExistingSource(relativePath);
        if (!string.IsNullOrWhiteSpace(sourcePath) && CanReadSource(sourcePath))
            return true;

        string readPath = ResolveReadPath(relativePath);
        error = IsMergedCachePath(readPath)
            ? "Map config resolves only to generated mergedmods data; no lossless writable mod source was found."
            : "Map config could not be resolved to a writable source file.";
        sourcePath = string.Empty;
        return false;
    }

    internal static string ResolveReadPath(string relativePath) =>
        string.IsNullOrWhiteSpace(relativePath)
            ? string.Empty
            : AssetManager.ResolveFilePath(relativePath);

    internal static void AtomicWriteAllText(string target, string content)
    {
        WorldModificationWorkspace.Write(target, content ?? string.Empty,
            (path, text) => AtomicWrite(path, temp => File.WriteAllText(temp, text)));
    }

    internal static void AtomicWriteAllLines(string target, IEnumerable<string> lines)
    {
        AtomicWriteAllText(target, string.Join(Environment.NewLine, lines ?? Array.Empty<string>()) + Environment.NewLine);
    }

    internal static bool CanReadSource(string path) => !string.IsNullOrWhiteSpace(path) && WorldModificationWorkspace.CanRead(path);
    internal static string ReadAllText(string path) => WorldModificationWorkspace.ReadAllText(path);
    internal static string[] ReadAllLines(string path) => WorldModificationWorkspace.ReadAllLines(path);

    internal static void SaveRoomSettings(RoomSettings settings)
    {
        string target = WorldModificationWorkspace.ResolveRoomSettings(settings.filePath);
        if (string.Equals(target, settings.filePath, StringComparison.OrdinalIgnoreCase)) { settings.Save(target, false); return; }
        string staged = Path.Combine(Path.GetTempPath(), "rainwright-room-" + Guid.NewGuid().ToString("N") + ".txt");
        try
        {
            settings.Save(staged, false);
            AtomicWriteAllText(target, File.ReadAllText(staged));
        }
        finally { if (File.Exists(staged)) File.Delete(staged); }
    }

    internal static void SaveRoomTemplate(RoomSettings settings, string templatePath)
    {
        string target = WorldModificationWorkspace.ResolveRoomSettings(templatePath);
        string staged = Path.Combine(Path.GetTempPath(), "rainwright-template-" + Guid.NewGuid().ToString("N") + ".txt");
        try
        {
            settings.Save(staged, true);
            AtomicWriteAllText(target, File.ReadAllText(staged));
        }
        finally { if (File.Exists(staged)) File.Delete(staged); }
    }

    private static void AtomicWrite(string target, Action<string> writeTemp)
    {
        if (string.IsNullOrWhiteSpace(target))
            throw new ArgumentException("Authoring target path is empty.", nameof(target));
        if (writeTemp == null)
            throw new ArgumentNullException(nameof(writeTemp));

        string directory = Path.GetDirectoryName(target);
        if (!string.IsNullOrWhiteSpace(directory))
            Directory.CreateDirectory(directory);

        string temp = target + ".tmp";
        string backup = target + ".bak";

        try
        {
            if (File.Exists(temp))
                File.Delete(temp);

            writeTemp(temp);

            bool hadOriginal = File.Exists(target);
            FileAttributes originalAttributes = hadOriginal ? File.GetAttributes(target) : FileAttributes.Normal;
            if (hadOriginal)
            {
                DryCycle.DevUI.DevTool.Persistence.EditorBackupFiles.Copy(target, backup, overwrite: true);
                File.Delete(target);
            }

            try
            {
                File.Move(temp, target);
            }
            catch
            {
                // Restore the exact pre-save file if commit fails after the original was removed.
                // Keep the .bak copy as an additional recovery artifact.
                if (hadOriginal && File.Exists(backup))
                {
                    try
                    {
                        if (File.Exists(target))
                            File.Delete(target);
                        File.Copy(backup, target, overwrite: true);
                        File.SetAttributes(target, originalAttributes);
                    }
                    catch (Exception restoreError)
                    {
                        global::DryCycle.DevUI.DevTool.Core.EditorDiagnostics.Error(
                            "World authoring rollback could not restore '" + target +
                            "' from backup.", restoreError);
                    }
                }
                throw;
            }
        }
        finally
        {
            try
            {
                if (File.Exists(temp))
                    File.Delete(temp);
            }
            catch (Exception cleanupError)
            {
                global::DryCycle.DevUI.DevTool.Core.EditorDiagnostics.Warning(
                    "World authoring temporary file cleanup failed for '" + temp + "'.",
                    cleanupError);
            }
        }
    }

    internal static bool IsMergedCachePath(string path) =>
        global::RainWright.IO.AuthoringSourcePaths.IsMergedCachePath(path);
}
